"""
export_c.py - export the trained model as a C header for microcontrollers
------------------------------------------------------------------------
The edge-AI endgame for PocketQ: turn the 8 trained floats into a
firmware/model.h that a $5 microcontroller can #include. The int8 version
is the one that goes on chip - 8 signed bytes, no floating point needed
for the weights (I still do float math for the rotations, but the model
itself fits in 8 bytes).

Run after train.py:
    python export_c.py

Writes firmware/model.h
"""

import json
import numpy as np


def main():
    with open("model.json") as f:
        model = json.load(f)

    lines = [
        "// firmware/model.h - generated by export_c.py, do not edit by hand",
        "// the entire trained quantum classifier. 8 weights.",
        "#ifndef POCKETQ_MODEL_H",
        "#define POCKETQ_MODEL_H",
        "",
        f"#define PQ_FEATURE_SCALE {model['feature_scale']!r}f",
        f"#define PQ_QUANT_SCALE   {model['quant_scale']!r}f",
        "",
        "// float32 weights",
        "static const float pq_params[8] = {",
    ]
    for i in range(0, 8, 4):
        chunk = ", ".join(f"{p!r}f" for p in model["params_float32"][i:i+4])
        lines.append("    " + chunk + ",")
    lines += [
        "};",
        "",
        "// int8 quantized weights (the ones a microcontroller would use)",
        "static const signed char pq_params_int8[8] = {",
        "    " + ", ".join(str(q) for q in model["params_int8"]) + ",",
        "};",
        "",
        "#endif // POCKETQ_MODEL_H",
        "",
    ]
    with open("firmware/model.h", "w") as f:
        f.write("\n".join(lines))
    print("wrote firmware/model.h (8 floats + 8 signed chars)")
    print("flash cost of the int8 model: 8 bytes")


if __name__ == "__main__":
    main()
